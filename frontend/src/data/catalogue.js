const INDEX_URL = "https://catalogue.uci.edu/allcourses/";

export function catalogueCourseUrl(department, number) {
    const subject = department.trim().replace(/\s+/g, " ").toUpperCase();
    const slug = SUBJECT_SLUGS.get(subject);
    if (!slug) return INDEX_URL;
    // Course listings don't have individual anchors. The subject page is the
    // fallback if the browser doesn't support text fragments or the course has moved.
    const text = encodeURIComponent(`${subject} ${number}.`).replaceAll("-", "%2D");
    return `${INDEX_URL}${slug}/#:~:text=${text}`;
}
